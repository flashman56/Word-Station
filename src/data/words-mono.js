const slugify = (form) => form.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

/**
 * 生成向后兼容的无词素词条。所有数组字段均显式保留，旧索引可安全遍历。
 */
function makeWord(form, pos, gloss, kind, origin, index) {
  const phrasePrefix = kind === 'phrase' ? 'phr-' : ''
  const word = {
    id: `w.${phrasePrefix}${slugify(form)}`,
    form,
    pos,
    gloss,
    morphs: [],
    chain: [],
    morphless: true,
    kind,
    origin,
    freqRank: index < 180 ? 100 + index * 10 : 2600 + (index - 180) * 8,
    cefr: kind === 'mono' ? (index < 100 ? 'A1' : 'A2') : kind === 'phrase' ? 'B2' : 'B1',
  }
  if (form === 'big') {
    word.phoneticBr = '/bɪɡ/'
    word.example = { en: 'The city has a big public park.', zh: '这座城市有一个很大的公共公园。' }
  }
  return word
}

